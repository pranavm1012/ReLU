# Dictionaries

# 1. Create the initial dictionary
book = {
    "title": "Harry Potter",
    "author": "J.K Rowling",
    "year": 2018,
    "price": 499.00
}

print("Original book dictionary:")
print(book)

# 2. Updating the price
book["price"] = 399.00

# 3. Adding a new key 'genre'
book["genre"] = "Self-Help / Productivity"

# 4. Printing the updated dictionary
print("\nUpdated book dictionary:")
print(book)
